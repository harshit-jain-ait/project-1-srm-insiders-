import { AIServiceResponse } from "./types";

export interface ProviderCallParams {
  systemInstruction: string;
  userPrompt: string;
  temperature?: number;
}

export class GeminiProvider {
  private getApiKey(): string | null {
    return process.env.GEMINI_API_KEY || process.env.GOOGLE_GENAI_API_KEY || null;
  }

  private getModel(): string {
    return process.env.GEMINI_MODEL || "gemini-3.5-flash-lite";
  }

  async executeStructuredPrompt<T>(
    params: ProviderCallParams
  ): Promise<AIServiceResponse<T>> {
    const apiKey = this.getApiKey();

    if (!apiKey) {
      return {
        success: false,
        code: "MISSING_API_KEY",
        error: "Server is missing GEMINI_API_KEY configuration.",
      };
    }

    const model = this.getModel();
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

    const requestPayload = {
      contents: [
        {
          role: "user",
          parts: [
            {
              text: `${params.systemInstruction}\n\n${params.userPrompt}`,
            },
          ],
        },
      ],
      generationConfig: {
        responseMimeType: "application/json",
        temperature: params.temperature ?? 0.2,
      },
    };

    try {
      // 25 second timeout
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 25000);

      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(requestPayload),
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        if (response.status === 429) {
          return {
            success: false,
            code: "RATE_LIMITED",
            error: "AI generation rate limit exceeded. Please wait a moment before trying again.",
          };
        }

        const errText = await response.text().catch(() => "");
        console.error(`[GeminiProvider] HTTP ${response.status}:`, errText);
        return {
          success: false,
          code: "PROVIDER_ERROR",
          error: `AI provider error (HTTP ${response.status}). Please try again later.`,
        };
      }

      const result = await response.json();
      const candidateText = result.candidates?.[0]?.content?.parts?.[0]?.text;

      if (!candidateText) {
        return {
          success: false,
          code: "INVALID_OUTPUT",
          error: "No candidate text generated by the AI model.",
        };
      }

      const parsed = JSON.parse(candidateText) as T;
      return {
        success: true,
        data: parsed,
      };
    } catch (err: unknown) {
      if (err instanceof Error && err.name === "AbortError") {
        return {
          success: false,
          code: "TIMEOUT",
          error: "AI request timed out after 25 seconds. Please try with shorter notes.",
        };
      }

      const errorMsg = err instanceof Error ? err.message : "Unknown error during AI execution";
      console.error("[GeminiProvider] Network/parsing error:", err);
      return {
        success: false,
        code: "INVALID_OUTPUT",
        error: `Failed to process AI response: ${errorMsg}`,
      };
    }
  }
}

export const geminiProvider = new GeminiProvider();
